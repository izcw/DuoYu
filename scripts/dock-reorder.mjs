import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile('src/features/desktop/DesktopDock.vue', 'utf8');
const drop = source.slice(source.indexOf('async function drop('), source.indexOf('</script>'));
const cloud = source.slice(source.indexOf('function cloudOrder()'), source.indexOf("window.addEventListener('duoyu-sync-preferences'"));
const compiled = ts.transpileModule(drop + cloud, { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText;
let release;
const stored = [];
const order = { value: ['home', 'workspace', 'b', 'a'] }, dragged = { value: 'a' }, savingOrder = { value: false }, pageDragError = { value: '' };
const database = { preferences: { put: row => new Promise(resolve => { release = () => { stored.push(row); resolve(); }; }) } };
const api = new Function('order', 'dragged', 'savingOrder', 'pageDragError', 'database', 'localStorage', 'scopedKey', 'storageKey', 'original', 'finish', 'readOrder', compiled + ';return {drop,cloudOrder};')(order, dragged, savingOrder, pageDragError, database, { setItem() {} }, k => k, 'dock', ['home','workspace','a','b'], () => { if (dragged.value) throw Error('drag end would restore old order'); }, () => ['home','workspace','a','b']);
const pending = api.drop({ preventDefault() {} });
api.cloudOrder();
assert.deepEqual(order.value, ['home','workspace','b','a']);
release(); await pending;
assert.deepEqual(stored[0].value, ['home','workspace','b','a']);
assert.equal(savingOrder.value, false);
console.log('PASS stale sync notification during reorder save does not reset order; displayed order persisted');
